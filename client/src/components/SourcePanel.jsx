/**
 * SourcePanel — lists the cited document passages used to produce the answer.
 * Text is always sourced from the database (via the API), never from model output.
 */
export default function SourcePanel({ sources }) {
  if (!sources?.length) return null;

  return (
    <div className="card" style={{ animationDelay: '0.1s' }}>
      <p className="sources-heading">📌 Source passages ({sources.length})</p>

      {sources.map((src, i) => (
        <div
          key={src.chunkId}
          className="source-item"
          id={`source-${i + 1}`}
          style={{ animationDelay: `${0.05 * i}s` }}
        >
          <div className="source-meta">Passage {i + 1}</div>
          <p className="source-text">"{src.text}"</p>
        </div>
      ))}

      <p style={{ fontSize: '0.72rem', color: 'var(--text-muted)', marginTop: '0.75rem' }}>
        These passages are retrieved directly from your document — not generated by AI.
      </p>
    </div>
  );
}
